# A list contains 5 strings. Convert all these strings to uppercase.



# Step 1: Define a list of strings
string_list = ["hello", "world", "python", "programming", "code"]
print("Original list of strings:", string_list)

# Step 2: Convert all strings to uppercase
uppercase_list = [string.upper() for string in string_list]
print("List of strings in uppercase:", uppercase_list)
